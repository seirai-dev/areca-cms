import { describe, expect, it } from 'vitest'
import ts from 'typescript'
import { generateContentTypes, paraglideSpecifier } from './generate-types.js'
import type { CollectionConfig, GlobalConfig } from './types.js'

const schema: Record<string, CollectionConfig> = {
  vacancies: {
    route: '/vacancies/$slug',
    routes: { nl: '/vacatures/$slug' },
    requiredLanguages: ['en'],
    fields: [
      { key: 'slug', label: 'Slug', type: 'slug', required: true },
      { key: 'title', label: 'Title', type: 'text', required: true, translatable: true },
      { key: 'salary', label: 'Salary', type: 'number', translatable: false },
    ],
  },
}

const globalSchema: Record<string, GlobalConfig> = {
  'home-page': {
    seo: true,
    requiredLanguages: ['en'],
    fields: [{ key: 'headline', label: 'Headline', type: 'text', translatable: true }],
  },
}

const languages = { main: 'nl', all: ['nl', 'en'] }

/** Runs the generated module with stubbed SDK imports and returns what it passed to createContent. */
function evaluate(source: string) {
  const { outputText, diagnostics } = ts.transpileModule(source, {
    reportDiagnostics: true,
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  })
  expect(diagnostics ?? []).toEqual([])
  const captured: { options?: Record<string, unknown> } = {}
  const moduleObject = { exports: {} as Record<string, unknown> }
  const require = (id: string) => {
    if (id === '@areca-cms/site-sdk/content') {
      return {
        createContent: (options: Record<string, unknown>) => {
          captured.options = options
          return {}
        },
      }
    }
    if (id.endsWith('/paraglide/runtime.js')) return { getLocale: () => 'nl' }
    throw new Error(`unexpected import ${id}`)
  }
  new Function('exports', 'require', 'module', outputText)(moduleObject.exports, require, moduleObject)
  return { exports: moduleObject.exports, options: captured.options }
}

describe('generateContentTypes: languages', () => {
  it('emits the languages constant and the Locale union', () => {
    const source = generateContentTypes({ schema, globalSchema, dir: 'x', languages })
    expect(source).toContain("export const languages = { main: 'nl', all: ['nl', 'en'] } as const")
    expect(source).toContain("export type Locale = 'nl' | 'en'")
  })

  it('registers languages next to schema and globals', () => {
    const source = generateContentTypes({ schema, globalSchema, dir: 'x', languages })
    expect(source).toContain(
      '    schema: typeof schema\n    globals: typeof globalSchema\n    languages: typeof languages\n',
    )
  })

  it('emits no languages block for a single-language site, so the output is unchanged', () => {
    const plain = generateContentTypes({ schema, globalSchema, dir: 'x' })
    expect(plain).not.toContain('languages')
    expect(plain).not.toContain('Locale')
    expect(generateContentTypes({ schema, globalSchema, dir: 'x', languages: null })).toBe(plain)
  })

  it('emits routes, requiredLanguages and translatable in the schema', () => {
    const source = generateContentTypes({ schema, globalSchema, dir: 'x', languages })
    expect(source).toContain("    routes: { nl: '/vacatures/$slug' },")
    expect(source).toContain("    requiredLanguages: ['en'],")
    expect(source).toContain("translatable: true")
    expect(source).toContain("translatable: false")
  })

  it('emits requiredLanguages for a global section', () => {
    const source = generateContentTypes({ schema, globalSchema, dir: 'x', languages })
    expect(source).toMatch(/homePage: \{\n    key: 'home-page'[\s\S]*requiredLanguages: \['en'\],/)
  })

  it('imports getLocale from the Paraglide runtime and passes it as the locale', () => {
    const source = generateContentTypes({
      schema,
      globalSchema,
      dir: 'x',
      languages,
      paraglideImport: '../paraglide/runtime.js',
    })
    expect(source).toContain("import { getLocale } from '../paraglide/runtime.js'")
    expect(source).toContain('  locale: getLocale,\n')
    const { options } = evaluate(source)
    expect(options?.locale).toBeTypeOf('function')
  })

  it('does not import Paraglide without the option', () => {
    const source = generateContentTypes({ schema, globalSchema, dir: 'x', languages })
    expect(source).not.toContain('getLocale')
  })

  it('golden output for a site with languages, Paraglide and a global section', () => {
    const source = generateContentTypes({
      schema,
      globalSchema,
      dir: 'src/generated/content',
      languages,
      paraglideImport: './paraglide/runtime.js',
    })
    expect(source).toBe(
      `// This file is generated by \`areca pull\`. Do not edit.
/* eslint-disable */
import { createContent } from '@areca-cms/site-sdk/content'
import type { Entry, Global } from '@areca-cms/site-sdk'
import { getLocale } from './paraglide/runtime.js'

export const schema = {
  vacancies: {
    key: 'vacancies',
    route: '/vacancies/$slug',
    routes: { nl: '/vacatures/$slug' },
    requiredLanguages: ['en'],
    fields: {
      /** Slug */
      slug: { key: 'slug', type: 'slug', required: true },
      /** Title */
      title: { key: 'title', type: 'text', required: true, translatable: true },
      /** Salary */
      salary: { key: 'salary', type: 'number', required: false, translatable: false },
    },
  },
} as const

export const globalSchema = {
  homePage: {
    key: 'home-page',
    seo: true,
    requiredLanguages: ['en'],
    fields: {
      /** Headline */
      headline: { key: 'headline', type: 'text', required: false, translatable: true },
    },
  },
} as const

export const languages = { main: 'nl', all: ['nl', 'en'] } as const
export type Locale = 'nl' | 'en'

declare module '@areca-cms/site-sdk' {
  interface Register {
    schema: typeof schema
    globals: typeof globalSchema
    languages: typeof languages
  }
}

export type VacanciesEntry = Entry<'vacancies'>
export type HomePageGlobal = Global<'homePage'>

export const content = createContent({
  schema,
  globalSchema,
  locale: getLocale,
  dir: process.env.ARECA_CONTENT_DIR ?? 'src/generated/content',
})
`,
    )
  })
})

describe('paraglideSpecifier', () => {
  it('is relative to the generated file and ends in .js', () => {
    expect(paraglideSpecifier('/app/src/generated/areca.gen.ts', '/app/src/paraglide/runtime.js')).toBe(
      '../paraglide/runtime.js',
    )
    expect(paraglideSpecifier('/app/src/areca.gen.ts', '/app/src/paraglide/runtime.ts')).toBe(
      './paraglide/runtime.js',
    )
  })
})
