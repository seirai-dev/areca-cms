import { afterEach, describe, expect, it } from 'vitest'
import ts from 'typescript'
import { generateContentTypes } from './generate-types.js'
import type { CollectionConfig } from './types.js'

const previousEnv = process.env.ARECA_CONTENT_DIR
afterEach(() => {
  if (previousEnv === undefined) delete process.env.ARECA_CONTENT_DIR
  else process.env.ARECA_CONTENT_DIR = previousEnv
})

const schema: Record<string, CollectionConfig> = {
  'blog-posts': {
    route: '/blog/$slug',
    label: 'Blog posts',
    fields: [
      { key: 'slug', label: 'Slug', type: 'slug', required: true },
      {
        key: 'title',
        label: 'Title',
        type: 'text',
        required: true,
        description: 'Shown as the page heading.',
      },
      { key: 'cover-image', label: 'Cover image', type: 'image' },
      {
        key: 'category',
        label: 'Category',
        type: 'select',
        options: ['news', 'guides'],
      },
      {
        key: 'author',
        label: 'Author',
        type: 'reference',
        collection: 'authors',
      },
    ],
  },
  authors: {
    route: '/authors/$slug',
    label: 'Authors',
    fields: [
      { key: 'slug', label: 'Slug', type: 'slug', required: true },
      { key: 'name', label: 'Name', type: 'text', required: true },
    ],
  },
}

