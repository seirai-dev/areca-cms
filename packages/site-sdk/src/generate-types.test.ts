/** Runs the generated module with a stubbed `createContent` and returns its exports. */
function evaluate(source: string): {
  exports: Record<string, unknown>
  options: { schema: Record<string, any>; dir: string } | undefined
} {
  const { outputText, diagnostics } = ts.transpileModule(source, {
    reportDiagnostics: true,
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  })
  expect(diagnostics ?? []).toEqual([])
  const captured: { options?: { schema: Record<string, any>; dir: string } } = {}
  const moduleObject = { exports: {} as Record<string, unknown> }
  const require = (id: string) => {
    if (id !== '@areca-cms/site-sdk/content') throw new Error(`unexpected import ${id}`)
    return {
      createContent: (options: { schema: Record<string, any>; dir: string }) => {
        captured.options = options
        return {}
      },
    }
  }
  new Function('exports', 'require', 'module', outputText)(
    moduleObject.exports,
    require,
    moduleObject,
  )
  return { exports: moduleObject.exports, options: captured.options }
}

describe('generateContentTypes', () => {
  it('matches the golden output for a small schema', () => {
    expect(generateContentTypes({ schema, dir: 'src/generated/content' })).toBe(
      GOLDEN,
    )
  })

  it('produces the same text regardless of collection insertion order', () => {
    const reversed = Object.fromEntries(Object.entries(schema).reverse())
    expect(generateContentTypes({ schema: reversed, dir: 'x' })).toBe(
      generateContentTypes({ schema, dir: 'x' }),
    )
  })

  it('keeps the schema field order and omits empty options', () => {
    const output = generateContentTypes({
      schema: {
        pages: {
          route: '/$slug',
          fields: [
            { key: 'slug', label: 'Slug', type: 'slug', required: true },
            { key: 'kind', label: 'Kind', type: 'select', options: [] },
          ],
        },
      },
      dir: 'x',
    })
    expect(output.indexOf('slug: {')).toBeLessThan(output.indexOf('kind: {'))
    expect(output).toContain("kind: { key: 'kind', type: 'select', required: false }")
    expect(output).not.toContain('options')
  })

  it('escapes */ in descriptions so the JSDoc cannot close early', () => {
    const output = generateContentTypes({
      schema: {
        pages: {
          route: '/$slug',
          fields: [
            {
              key: 'body',
              label: 'Body',
              type: 'text',
              required: false,
              description: 'Wrap code in /* and */ markers',
            },
          ],
        },
      },
      dir: 'x',
    })
    const line = output
      .split('\n')
      .find((text) => text.includes('Body — Wrap code'))
    expect(line).toBeDefined()
    expect(line!.trim().startsWith('/**')).toBe(true)
    expect(line!.trim().endsWith('*/')).toBe(true)
    expect(line!.split('*/').length - 1).toBe(1)
    expect(evaluate(output).exports.schema).toBeDefined()
  })

  it('escapes quotes in collection labels and the dir literal', () => {
    const label = "Authors' \"bios\" \\ notes"
    const dir = "it's \"quoted\"\\dir"
    delete process.env.ARECA_CONTENT_DIR
    const output = generateContentTypes({
      schema: {
        authors: {
          route: '/$slug',
          label,
          fields: [{ key: 'slug', label: 'Slug', type: 'slug', required: true }],
        },
      },
      dir,
    })
    const { exports, options } = evaluate(output)
    expect((exports.schema as Record<string, any>).authors.label).toBe(label)
    expect(options?.dir).toBe(dir)
  })

  it('emits an empty schema, still registered, when there are no collections', () => {
    expect(generateContentTypes({ schema: {}, dir: 'src/generated/content' })).toBe(
      `// This file is generated by \`areca pull\`. Do not edit.
/* eslint-disable */
import { createContent } from '@areca-cms/site-sdk/content'
import type { Entry } from '@areca-cms/site-sdk'

export const schema = {} as const

declare module '@areca-cms/site-sdk' {
  interface Register {
    schema: typeof schema
  }
}

export const content = createContent({
  schema,
  dir: process.env.ARECA_CONTENT_DIR ?? 'src/generated/content',
})
`,
    )
  })
})
