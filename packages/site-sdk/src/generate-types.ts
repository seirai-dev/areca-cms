import { dirname, relative, resolve } from 'node:path'
import {
  camelCollections,
  camelGlobals,
  toCamelKey,
  type CamelCollection,
  type CamelGlobal,
} from './camel-case.js'
import type { CollectionConfig, GlobalConfig, SiteLanguages } from './types.js'

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

export type GenerateContentTypesOptions = {
  schema: Record<string, CollectionConfig>
  globalSchema?: Record<string, GlobalConfig>
  dir: string
  /**
   * The site's content languages. Omit or null for a single-language site:
   * the output then has no `languages` block and no Locale type.
   */
  languages?: SiteLanguages | null
  /**
   * Module specifier of the Paraglide runtime, relative to the generated file
   * (e.g. `../paraglide/runtime.js`). Its `getLocale` becomes the content locale.
   */
  paraglideImport?: string
}

/**
 * Source of `areca.gen.ts` (spec section 4). Deterministic: collections and
 * site content sections are sorted by camel key and fields keep their schema
 * order. Lines are never wrapped, so the output does not depend on a formatter.
 */
export function generateContentTypes(options: GenerateContentTypesOptions): string {
  const collections = camelCollections(options.schema).sort(byCamel)
  const globals = camelGlobals(options.globalSchema ?? {}).sort(byCamel)
  const languages = options.languages ?? null

  const schemaLines =
    collections.length === 0
      ? ['export const schema = {} as const']
      : [
          'export const schema = {',
          ...collections.flatMap(collectionLines),
          '} as const',
        ]

  const globalSchemaLines =
    globals.length === 0
      ? ['export const globalSchema = {} as const']
      : [
          'export const globalSchema = {',
          ...globals.flatMap(globalLines),
          '} as const',
        ]

  const languageLines = languages === null ? [] : languagesLines(languages)

  const typeLines = [
    ...collections.map(
      ({ camel }) => `export type ${capitalise(camel)}Entry = Entry<'${camel}'>`,
    ),
    ...globals.map(
      ({ camel }) => `export type ${capitalise(camel)}Global = Global<'${camel}'>`,
    ),
  ]

  const registerLines = [
    '    schema: typeof schema',
    '    globals: typeof globalSchema',
    ...(languages === null ? [] : ['    languages: typeof languages']),
  ]

  const sdkImports = globals.length === 0 ? 'Entry' : 'Entry, Global'

  return [
    '// This file is generated by `areca pull`. Do not edit.',
    '/* eslint-disable */',
    "import { createContent } from '@areca-cms/site-sdk/content'",
    `import type { ${sdkImports} } from '@areca-cms/site-sdk'`,
    ...(options.paraglideImport !== undefined
      ? [`import { getLocale } from ${quote(options.paraglideImport)}`]
      : []),
    '',
    ...schemaLines,
    '',
    ...globalSchemaLines,
    '',
    ...languageLines,
    ...(languageLines.length > 0 ? [''] : []),
    "declare module '@areca-cms/site-sdk' {",
    '  interface Register {',
    ...registerLines,
    '  }',
    '}',
    '',
    ...(typeLines.length > 0 ? [...typeLines, ''] : []),
    'export const content = createContent({',
    '  schema,',
    '  globalSchema,',
    ...(options.paraglideImport !== undefined ? ['  locale: getLocale,'] : []),
    `  dir: process.env.ARECA_CONTENT_DIR ?? ${quote(options.dir)},`,
    '})',
    '',
  ].join('\n')
}

/**
 * Module specifier for the Paraglide runtime, relative to the generated file
 * and ending in `.js`. `target` is an absolute path to the runtime module.
 */
export function paraglideSpecifier(generatedFile: string, target: string): string {
  const relativePath = relative(dirname(resolve(generatedFile)), resolve(target)).split('\\').join('/')
  const withJs = relativePath.replace(/\.(?:ts|mts|cts|tsx|js|mjs|cjs)$/, '') + '.js'
  return withJs.startsWith('.') ? withJs : `./${withJs}`
}

/** `languages` and the `Locale` union. Main first, then the site order. */
function languagesLines(languages: SiteLanguages): string[] {
  const all = languages.all.map(quote).join(', ')
  return [
    `export const languages = { main: ${quote(languages.main)}, all: [${all}] } as const`,
    `export type Locale = ${languages.all.map(quote).join(' | ')}`,
  ]
}

function byCamel(a: { camel: string }, b: { camel: string }): number {
  return a.camel < b.camel ? -1 : a.camel > b.camel ? 1 : 0
}

function collectionLines({ raw, camel, config, fields }: CamelCollection): string[] {
  const lines: string[] = []
  if (config.label !== undefined) lines.push(`  /** ${commentText(config.label)} */`)
  lines.push(`  ${propertyKey(camel)}: {`, `    key: ${quote(raw)},`)
  if (config.label !== undefined) lines.push(`    label: ${quote(config.label)},`)
  lines.push(`    route: ${quote(config.route)},`)
  if (config.routes !== undefined && Object.keys(config.routes).length > 0) {
    const entries = Object.entries(config.routes).map(
      ([tag, pattern]) => `${propertyKey(tag)}: ${quote(pattern)}`,
    )
    lines.push(`    routes: { ${entries.join(', ')} },`)
  }
  if (config.requiredLanguages !== undefined && config.requiredLanguages.length > 0) {
    lines.push(`    requiredLanguages: [${config.requiredLanguages.map(quote).join(', ')}],`)
  }
  lines.push(...fieldsLines(fields))
  lines.push('  },')
  return lines
}

function globalLines({ raw, camel, config, fields }: CamelGlobal): string[] {
  const lines: string[] = []
  if (config.label !== undefined) lines.push(`  /** ${commentText(config.label)} */`)
  lines.push(`  ${propertyKey(camel)}: {`, `    key: ${quote(raw)},`)
  if (config.label !== undefined) lines.push(`    label: ${quote(config.label)},`)
  lines.push(`    seo: ${config.seo === true},`)
  if (config.previewPath !== undefined) {
    lines.push(`    previewPath: ${quote(config.previewPath)},`)
  }
  if (config.requiredLanguages !== undefined && config.requiredLanguages.length > 0) {
    lines.push(`    requiredLanguages: [${config.requiredLanguages.map(quote).join(', ')}],`)
  }
  lines.push(...fieldsLines(fields))
  lines.push('  },')
  return lines
}

function fieldsLines(fields: CamelCollection['fields']): string[] {
  if (fields.length === 0) return ['    fields: {},']
  const lines = ['    fields: {']
  for (const { raw: fieldKey, camel: fieldName, field } of fields) {
    const label =
      field.description !== undefined
        ? `${field.label} — ${field.description}`
        : field.label
    const parts = [
      `key: ${quote(fieldKey)}`,
      `type: ${quote(field.type)}`,
      `required: ${field.required === true}`,
    ]
    if ('options' in field && field.options && field.options.length > 0) {
      parts.push(`options: [${field.options.map(quote).join(', ')}]`)
    }
    if ('collection' in field) {
      parts.push(`collection: ${quote(toCamelKey(field.collection))}`)
    }
    if (field.group !== undefined) parts.push(`group: ${quote(field.group)}`)
    if (field.translatable !== undefined) parts.push(`translatable: ${field.translatable === true}`)
    lines.push(
      `      /** ${commentText(label)} */`,
      `      ${propertyKey(fieldName)}: { ${parts.join(', ')} },`,
    )
  }
  lines.push('    },')
  return lines
}

/** Flattens text to one line and escapes the comment terminator for a JSDoc comment. */
function commentText(text: string): string {
  return text.replace(/\s+/g, ' ').trim().replace(/\*\//g, '*\\/')
}

function capitalise(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function propertyKey(key: string): string {
  return IDENTIFIER.test(key) ? key : quote(key)
}

function quote(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
  return "'" + escaped + "'";
}
