// Side-effect module: MUST be imported first by benchmark.ts. It enforces the
// safety gate and pins DATABASE_URL before `#/env` (which would otherwise load
// .env.local) is evaluated.
import { existsSync } from 'node:fs'
import { registerHooks } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseArgs } from 'node:util'

export const args = parseArgs({
  options: {
    'database-url': { type: 'string' },
    scale: { type: 'string', default: '1' },
    runs: { type: 'string', default: '7' },
    json: { type: 'string' },
    keep: { type: 'boolean', default: false },
    'skip-seed': { type: 'boolean', default: false },
  },
  allowPositionals: true,
}).values

// ---------------------------------------------------------------- safety gate
if (process.env.ARECA_BENCHMARK !== '1') {
  console.error(
    'Refusing to run: set ARECA_BENCHMARK=1 to confirm this seeds synthetic data.',
  )
  process.exit(1)
}
const databaseUrl = args['database-url'] ?? process.env.DATABASE_URL
if (!databaseUrl) {
  console.error('Refusing to run: pass --database-url (or set DATABASE_URL).')
  process.exit(1)
}
const dbName = decodeURIComponent(new URL(databaseUrl).pathname.slice(1))
if (!/bench|test/i.test(dbName)) {
  console.error(
    `Refusing to run: database name "${dbName}" must contain "bench" or "test".`,
  )
  process.exit(1)
}
process.env.DATABASE_URL = databaseUrl
// The measured code paths never talk to S3/SMTP/Redis; the env schema just
// needs values to exist.
const defaults: Record<string, string> = {
  BETTER_AUTH_SECRET: 'benchmark-secret',
  BETTER_AUTH_URL: 'http://localhost:3999',
  APP_URL: 'http://localhost:3999',
  S3_ENDPOINT: 'http://localhost:1',
  S3_REGION: 'us-east-1',
  S3_BUCKET: 'bench',
  S3_ACCESS_KEY: 'bench',
  S3_SECRET_KEY: 'bench',
  SMTP_HOST: 'localhost',
  SMTP_PORT: '1',
  SMTP_FROM: 'bench@areca.local',
  DOKPLOY_CREDENTIALS_ENCRYPTION_KEY:
    'AQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQE=',
  WORKER_ENABLED: 'false',
}
for (const [k, v] of Object.entries(defaults)) process.env[k] ??= v

export const benchDbName = dbName

// `#/paraglide/*` is generated by the Vite plugin and needs `import.meta.env`,
// which plain Node lacks. Point it at the Node-friendly compile from
// `pnpm run paraglide:scripts`. Sync hooks are used because tsx's own sync
// resolver would otherwise win over `module.register()` hooks.
const paraglideDir = new URL(
  '../../node_modules/.cache/areca-scripts/paraglide/',
  import.meta.url,
)
registerHooks({
  resolve(specifier, context, nextResolve) {
    const prefix = '#/paraglide/'
    if (!specifier.startsWith(prefix)) return nextResolve(specifier, context)
    const target = new URL(
      `${specifier.slice(prefix.length).replace(/\.js$/, '')}.js`,
      paraglideDir,
    )
    if (!existsSync(fileURLToPath(target))) {
      throw new Error(
        'Paraglide messages for scripts are missing. Run `pnpm run paraglide:scripts` first.',
      )
    }
    return {
      url: pathToFileURL(fileURLToPath(target)).href,
      shortCircuit: true,
    }
  },
})
